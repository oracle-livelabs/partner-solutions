'use strict';
// Run explicitly against a READY synthetic preview; never prints access cookies.
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const base=process.env.DETECTIVE_PREVIEW_URL||'http://127.0.0.1:18707';
const batch=process.env.DETECTIVE_TEST_BATCH||'DR-20260925-4a92944f-9986-4202';
const root='/api/data-room/batches/'+batch+'/room';
const headers={'X-Demo-User':'statewide_admin','Content-Type':'application/json'};
(async()=>{
 const state=await (await fetch(base+root,{headers})).json();
 assert(state.ready,'A completed preview run is required');
 const id=state.ready.id;
 const unchanged=await fetch(base+root,{method:'POST',headers,body:'{}'});
 assert.equal(unchanged.status,200);const same=await unchanged.json();
 assert.equal(same.job.id,id);assert.equal(same.reused,true);
 const denied=await fetch(base+root,{method:'POST',headers:{...headers,'X-Demo-User':'read_only_viewer'},body:'{}'});
 assert.equal(denied.status,403);
 const access=await fetch(base+root+'/runs/'+id+'/access',{method:'POST',headers});
 assert.equal(access.status,200);
 const cookie=access.headers.get('set-cookie').split(';')[0],links=await access.json();
 assert(!links.view.includes('?'));assert(access.headers.get('set-cookie').includes('HttpOnly'));
 const noCookie=await fetch(base+links.view);assert.equal(noCookie.status,401);
 const room=await fetch(base+links.view,{headers:{Cookie:cookie}});
 assert.equal(room.status,200);assert(room.headers.get('content-security-policy').includes("default-src 'none'"));
 assert((await room.text()).includes(batch));
 const mp4=links.view.replace('Virtual-Detective-Room.html','briefing/Case-Overview.mp4');
 const range=await fetch(base+mp4,{headers:{Cookie:cookie,Range:'bytes=0-1023'}});
 assert.equal(range.status,206);assert.equal((await range.arrayBuffer()).byteLength,1024);
 const download=await fetch(base+links.download,{method:'HEAD',headers:{Cookie:cookie}});
 assert.equal(download.status,200);
 const disposition=download.headers.get('content-disposition');
 assert(disposition.includes(batch)&&disposition.includes(id));
 const transferred=await fetch(base+links.download,{headers:{Cookie:cookie},signal:AbortSignal.timeout(60000)});
 assert.equal(transferred.status,200);
 const zip=Buffer.from(await transferred.arrayBuffer());
 assert.equal(zip.length,Number(transferred.headers.get('content-length')));
 assert.equal(zip.readUInt32LE(0),0x04034b50);
 const zipSHA256=crypto.createHash('sha256').update(zip).digest('hex');
 if(process.env.DETECTIVE_EXPECTED_ZIP_SHA)assert.equal(zipSHA256,process.env.DETECTIVE_EXPECTED_ZIP_SHA);
 const tampered=await fetch(base+links.view,{headers:{Cookie:cookie+'x'}});
 assert.equal(tampered.status,401);
 const forbidden=await fetch(base+links.view.replace('Virtual-Detective-Room.html','private-model-responses/001.json'),{headers:{Cookie:cookie}});
 assert.equal(forbidden.status,404);
 console.log(JSON.stringify({status:'passed',batch,run:id,zipBytes:zip.length,zipSHA256,checks:['READY reuse without generation','read-only generation denied','cookie-scoped new-window access','unauthenticated and tampered access denied','CSP and source batch identity','MP4 byte ranges','full ZIP transfer and batch/run-specific filename','private model response not served']},null,2));
})().catch(e=>{console.error(e.message);process.exitCode=1;});
